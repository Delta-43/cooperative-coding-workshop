// Checks the frontend's message types against the contract's examples.
// Every contract/examples/*.json becomes a typed fixture (`{ ... } satisfies GameState`), so
// tsc fails when the contract has a field the types lack, or the types require a field the
// contract does not send. Run with `npm test`.
import { execFileSync } from 'node:child_process'
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const frontend = join(dirname(fileURLToPath(import.meta.url)), '..')
const examples = join(frontend, '..', 'contract', 'examples')
const out = join(frontend, '.contract-check')

const typeFor = (file) => (file.startsWith('state-') ? 'GameState' : file === 'error.json' ? 'ServerError' : 'ClientMessage')

const files = readdirSync(examples).filter((f) => f.endsWith('.json')).sort()
const lines = [
  '// Generated by scripts/contract-check.mjs from contract/examples. Do not edit.',
  "import type { ClientMessage, GameState, ServerError } from '../src/contract'",
  '',
]
for (const file of files) {
  const name = file.replace(/\.json$/, '').replace(/\W/g, '_')
  const json = JSON.stringify(JSON.parse(readFileSync(join(examples, file), 'utf8')), null, 2)
  lines.push(`// contract/examples/${file}`, `export const ${name} = ${json} satisfies ${typeFor(file)}`, '')
}
mkdirSync(out, { recursive: true })
writeFileSync(join(out, 'examples.ts'), lines.join('\n'))

try {
  execFileSync(join(frontend, 'node_modules', '.bin', 'tsc'), ['-p', join(frontend, 'tsconfig.contract.json')], { stdio: 'inherit' })
} catch {
  console.error('\nThe frontend types in src/contract.ts do not match contract/examples. Change the contract first, then the types.')
  process.exit(1)
}
console.log(`Contract check: ${files.length} examples match the frontend types.`)
